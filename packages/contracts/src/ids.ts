/**
 * IDs are UUID v7, generated in the application (ADR-022, PLAN.md §5): known before the insert,
 * time-ordered for index locality, and the same code in the API, the worker and the browser.
 * A v7 ID shows when it was created, to the millisecond. Never use one as a secret; share links
 * get separate random tokens.
 */
import { v7 } from "uuid";
import { z } from "zod";

export const idSchema = z.uuidv7().meta({
  id: "Id",
  description: "A UUID v7, generated by the application (ADR-022).",
  example: "019ab8c2-5d4e-7f10-8a2b-3c4d5e6f7a8b",
});

export type Id = z.infer<typeof idSchema>;

/** A new UUID v7. IDs from one process are strictly increasing, even within one millisecond. */
export function newId(): Id {
  return v7();
}
